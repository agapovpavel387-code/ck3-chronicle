  window.applyI18n = (root) => {
    for (const node of (root || document).querySelectorAll('[data-i18n]')) {
      const key = node.getAttribute('data-i18n');
      const text = window.t(key, node.textContent);
      if (text) node.textContent = text;
    }
    for (const node of (root || document).querySelectorAll('[data-i18n-title]')) {
      node.setAttribute('title', window.t(node.getAttribute('data-i18n-title'), node.getAttribute('title') || ''));
    }
    document.documentElement.lang = current;
  };
