/* Словарь заметок: игровые формулировки → язык летописи.
   Правило = [регулярка по типу, функция (ctx) → строка].
   ctx: { year, name, female, other, type }. */

(function () {
  'use strict';

  const g = (female, male, fem) => (female ? fem : male);
  const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s);
  const low = (s) => (s ? s[0].toLowerCase() + s.slice(1) : s);

  const rules = [
    // --- дом и двор
    [/кошка умерла/i, (c) => `В лето ${c.year}-е пала любимая кошка; ${c.name} ${g(c.female, 'счёл', 'сочла')} это дурным знамением.`],
    [/любимая игрушка/i, (c) => `${c.name} хранил${g(c.female, '', 'а')} любимую игрушку с детства.`],
    [/кормилица умерла/i, (c) => `${c.name} ${g(c.female, 'оплакал', 'оплакала')} кормилицу.`],
    [/пикник/i, (c) => `${c.name} устроил${g(c.female, '', 'а')} пир на весь двор.`],

    // --- пиры, свадьбы, состязания
    [/питейн|чаш/i, (c) => `${c.name} ${g(c.female, 'одержал', 'одержала')} верх над недругом в состязании чашами.`],
    [/победа в состязании/i, (c) => `${c.name} ${g(c.female, 'победил', 'победила')} в состязании.`],
    [/поженились на большой свадьбе/i, (c) => `${c.name} ${g(c.female, 'справил', 'справила')} большую свадьбу.`],
    [/больш[а-я]* свадьб/i, (c) => `${c.name} ${g(c.female, 'был', 'была')} на большой свадьбе.`],

    // --- рыцарство и война
    [/акколад/i, (c) => `${c.name} ${g(c.female, 'был посвящён', 'была посвящена')} в рыцари.`],
    [/подопечн/i, (c) => `${c.name} ${g(c.female, 'воспитал', 'воспитала')} ${c.other ? c.other : 'достойного наследника'}.`],
    [/успешное убийство/i, (c) => `${c.name} ${g(c.female, 'совершил', 'совершила')} убийство${c.other ? ` — погиб ${c.other}` : ''}, и оно сошло с рук.`],
    [/оставили умирать после покушения/i, (c) => `${c.name} ${g(c.female, 'пал', 'пала')} от руки убийц в пути.`],
    [/героическая смерть персонажа\s+(.+)/i, (c, m) => `${cap(m[1])} ${g(c.female, 'погиб', 'погибла')} смертью героя.`],
    [/убитый зверь/i, (c) => `${c.name} ${g(c.female, 'добыл', 'добыла')} зверя на охоте.`],
    [/удачная охота/i, (c) => `Охота ${c.name} была удачной.`],
    [/обет завоевания/i, (c) => `${c.name} ${g(c.female, 'дал', 'дала')} обет завоевания.`],

    // --- плен, заложники, мир
    [/взятый заложник/i, (c) => `${c.name} ${g(c.female, 'взял', 'взяла')} заложника.`],
    [/отправленный заложник/i, (c) => `${c.name} ${g(c.female, 'отправил', 'отправила')} заложника.`],
    [/возвращение заложника/i, (c) => `${c.name} ${g(c.female, 'вернул', 'вернула')} заложника.`],
    [/^(.+?) соглашается на статус-кво/i, (c, m) => `${cap(m[1])} и ${c.name} — мир на условиях статус-кво.`],

    // --- верность, вражда, любовь
    [/перестали быть друзьями/i, (c) => `${c.name} и ${c.other || 'прежний друг'} рассорились.`],
    [/перестали быть соперниками/i, (c) => `${c.name} и ${c.other || 'прежний недруг'} помирились.`],
    [/родственными душами/i, (c) => `${c.name} ${g(c.female, 'обрёл', 'обрела')} родственную душу.`],
    [/заклятыми врагами|начата вражда/i, (c) => `${c.name} ${g(c.female, 'нажил', 'нажила')} заклятого врага.`],
    [/разрыв любовных отношений/i, (c) => (c.other ? `${c.name} и ${c.other} расстались.` : 'Любовная связь прервалась.')],
    [/смерть родственной души|смерть лучшего друга/i, (c) => `${c.name} ${g(c.female, 'потерял', 'потеряла')} близкого человека.`],

    // --- вера и странствия
    [/хадж|паломнич/i, (c) => `${c.name} ${g(c.female, 'совершил', 'совершила')} паломничество.`],
    [/посещен город/i, (c) => `${c.name} ${g(c.female, 'побывал', 'побывала')} в большом городе.`],
    [/поиски приключений/i, (c) => `${c.name} ${g(c.female, 'ушёл', 'ушла')} искать приключений.`],

    // --- дитя и семья
    [/детские мучения/i, (c) => `Детство ${c.name} было тяжким.`],
    [/смерть ребенка по вине свиньи/i, (c) => `В семье ${c.name} погиб ребёнок — виной тому свинья.`],
    [/унижение/i, (c) => `${c.name} ${g(c.female, 'пережил', 'пережила')} унижение на коронации.`],
    [/подарили милое украшение/i, (c) => `${c.name} ${g(c.female, 'получил', 'получила')} в дар украшение.`],
  ];

  // Служебные воспоминания: о свойствах, обучении и экзаменах — не материал хроники.
  const skip = [
    /детское образование/i,
    /экзамен/i,
    /свойство/i,
    /благочестивый родитель|знаменитый родитель/i,
    /^[А-ЯЁ][а-яё-]+\s+[А-ЯЁ][а-яё-]+$/, // тип-имя без глагола
  ];

  function noteText(type, ctx) {
    const text = String(type || '').trim();
    if (!text) return '';
    if (/[a-z]/i.test(text)) return ''; // непереведённые ключи
    for (const pattern of skip) {
      if (pattern.test(text)) return '';
    }
    for (const [pattern, make] of rules) {
      const match = text.match(pattern);
      if (match) return make(ctx, match);
    }
    // Без правила — сдержанная строка без выдумки.
    // Регистр не трогаем: в начале игровой заметки часто стоит имя («Гондэр Странный…»).
    return `В лето ${ctx.year}-е: ${text}${ctx.name ? ` — ${ctx.name}` : ''}.`;
  }

  window.noteText = noteText;
  window.NOTE_RULES_COUNT = rules.length;
})();
